export interface EducationalGenerationParams {
  contentType: string;
  topic: string;
  subject: string;
  gradeLevel: string;
  learningStrategy?: string;
  tone?: string;
  length?: string;
  aspects?: string[];
}

export function generateEducationalFallback(params: EducationalGenerationParams): string {
  const {
    contentType,
    topic,
    subject,
    gradeLevel,
    learningStrategy = "التعلم النشط والاستقصاء الموجه",
    tone = "تشجيعي وتحفيزي للطلاب",
    aspects = [],
  } = params;

  const dateStr = new Date().toLocaleDateString("ar-SA", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const additionalPoints = aspects.length > 0
    ? `\n\n### 📌 معايير ومحاور التركيز الإضافية:\n${aspects.map((a) => `- ${a}`).join("\n")}`
    : "";

  if (contentType === "خطة درس نموذجي") {
    return `# 📚 خطة درس نموذجي متكاملة: ${topic}

- **المادة الدراسية:** ${subject}
- **الصف والمرحلة:** ${gradeLevel}
- **المدة الزمنية:** 45 دقيقة (حصة صفية كاملة)
- **استراتيجية التدريس:** ${learningStrategy}
- **الأسلوب التربوي:** ${tone}
- **تاريخ الإعداد:** ${dateStr}

---

## 🎯 نواتج التعلم المستهدفة (وفق مستويات تصنيف بلوم):

1. **الهدف المعرفي (التذكر والفهم):** أن يتعرف الطالب على المفاهيم والأسس الجوهرية لدرس **(${topic})** ويعرّف مصطلحاته العلمية بدقة لا تقل عن 85%.
2. **الهدف المهاري (التطبيق والتحليل):** أن يحلل الطالب عناصر درس **(${topic})** ويطبقها في حل أنشطة وتدريبات صفية مرتبطة بواقع الحياة.
3. **الهدف الوجداني (القيم والاتجاهات):** أن يقدّر الطالب أهمية توظيف معارف **(${topic})** ويتعاون بإيجابية مع زملائه في الأنشطة الصفية.

---

## 🚀 1. التهيئة الحافزة وإثارة الدافعية (5 دقائق)
- **السؤال الاستهلالي المحفز للتفكير الناقد:**
  > "كيف يرتبط موضوع **(${topic})** بحياتنا اليومية ومحيطنا العملي؟ وماذا يحدث لو لم نطبق هذه المفاهيم؟"
- **نشاط التهيئة:** عرض موقف تعليمي قصير أو صورة تفاعلية تستثير التفكير والفضول العلمي، مع تدوين الإجابات الأولية للطلاب على السبورة.

---

## 📖 2. استراتيجيات التدريس وسير الأنشطة الصفية (25 دقيقة)

### النشاط الأول: الاستكشاف الموجه واستراتيجية (${learningStrategy}) (10 دقائق)
- **الهدف:** تفكيك المفاهيم الأساسية لدرس **(${topic})**.
- **إجراءات المعلم:** طرح المشكلة وتوجيه الطلاب للبحث واستخلاص القواعد والمبادئ خطوة بخطوة.
- **دور الطلاب:** العمل في مجموعات ثنائية لتبادل الأفكار وتدوين الملاحظات والمقارنة.

### النشاط الثاني: التعلم التعاوني والتطبيق العملي (15 دقيقة)
- **تقسيم المجموعات (مراعاة الفروق الفردية):**
  - **مجموعة التأسيس والتعريف:** استخراج المفاهيم والمصطلحات الأساسية للدرس.
  - **مجموعة التطبيق والأمثلة:** حل مسائل وتطبيقات ونماذج متنوعة عن **(${topic})**.
  - **مجموعة التحدي والإبداع:** ابتكار مسألة جديدة أو تقديم تشبيه ذهني لشرح الموضوع لبقية الطلاب.

---

## 📝 3. التقويم التكويني والتحقق من الفهم (10 دقائق)

### أ. أسئلة سريعة لقياس الأهداف:
1. **(سؤال موضوعي):** بيّن صحة أو خطأ المفهوم الرئيسي لدرس **(${topic})** مع التعليل.
2. **(سؤال مقالي تحليلي):** اذكر خطوتين أساسيتين لتطبيق **(${topic})** مع ضرب مثال توضيحي.

### ب. مراعاة الفروق الفردية:
- **دعم الطلاب المحتاجين للتمكين:** تقديم بطاقة إرشادية تتضمن خرائط مفاهيم ملخصة.
- **إثراء الطلاب المتقدمين:** تكليفهم بربط الدرس بأمثلة من البيئة المحيطة أو التكنولوجيا الحديثة.

---

## 🏁 4. الغلق وتذكرة الخروج (5 دقائق)
- **تذكرة الخروج (Exit Ticket):** يُدوّن كل طالب بطاقة موجزة تتضمن:
  1. أهم فكرة أو مهارة اكتسبها اليوم حول **(${topic})**.
  2. نقطة أو استفسار يرغب في استيضاحه مستقبلاً.
- **الواجب المنزلي الإثرائي:** حل التمرين التفاعلي في كتاب الطالب، وإعداد بطاقة تلخيصية عن الدرس.${additionalPoints}
`;
  }

  if (contentType === "اختبار وأسئلة تقويمية") {
    return `# 📝 اختبار وتقويم تحصيلي مقنن: ${topic}

- **المادة الدراسية:** ${subject}
- **المرحلة والصف:** ${gradeLevel}
- **الزمن المخصص:** 30 دقيقة
- **الدرجة الكلية:** 20 درجة
- **نموذج التقويم:** أسئلة موضوعية ومقالية وفق المعايير التربوية

---

### القسم الأول: أسئلة الاختيار من متعدد (6 درجات - لكل فقرة درجة ونصف)
*اختر الإجابة الصحيحة من بين الخيارات التالية:*

1. **التعريف الأدق لمفهوم (${topic}) هو:**
   - [أ] التعريف الأولي العام
   - [ب] الاستخدام العلمي التطبيقي الصحيح *(الإجابة الصحيحة)*
   - [ج] حالة خاصة ونادرة
   - [د] المفهوم المعاكس للموضوع

2. **من أهم خصائص ومميزات (${topic}) التي نلاحظها عملياً:**
   - [أ] الدقة والترابط المنطقي *(الإجابة الصحيحة)*
   - [ب] العشوائية وغياب الترتيب
   - [ج] محدودية التطبيق
   - [د] صعوبة القياس

3. **عند تطبيق استراتيجيات (${topic}) في مواقف جديدة، فإن الخطوة الأولى هي:**
   - [أ] تحديد المعطيات والهدف المطلوب بدقة *(الإجابة الصحيحة)*
   - [ب] التسرع في استنتاج النتائج
   - [ج] تجاهل الفروق الأساسية
   - [د] الاكتفاء بالحفظ المجرد

4. **تكمن الفائدة الكبرى لتعلم (${topic}) في:**
   - [أ] تنمية التفكير الناقد وحل المشكلات الحياتية *(الإجابة الصحيحة)*
   - [ب] أداء الاختبارات فقط
   - [ج] تكرار التجارب دون فهم
   - [د] تقليل المهارات اليدوية

---

### القسم الثاني: أسئلة الصواب والخطأ مع تصحيح الخطأ (6 درجات)
1. **(   )** يُعتبر فهم **(${topic})** ركيزة أساسية في منهج ${subject} لبناء المهارات اللاحقة. *(صحيح)*
2. **(   )** لا توجد أي علاقة بين موضوع **(${topic})** والتطبيقات الواقعية في حياتنا اليومية. *(خطأ - بل يرتبط ارتباطاً وثيقاً بالحياة العملية)*
3. **(   )** تتطلب معالجة مسائل **(${topic})** التدرج في التفكير من السهل إلى المركب. *(صحيح)*

---

### القسم الثالث: الأسئلة المقالية والمهارية (8 درجات)

#### السؤال الأول (4 درجات):
اشرح بأسلوبك العلمي الواضح المفهوم الأساسي لـ **(${topic})** مبيناً مثالاً تطبيقياً واحداً من واقعك المعاش.

#### السؤال الثاني (4 درجات):
قارن بين حالتين مختلفتين من حالات **(${topic})** موضحاً أوجه الشبه والاختلاف في جدول منظم.

---

### 📋 نموذج الإجابة وسلم تقدير الدرجات (Rubric):
| رقم السؤال | نوع السؤال | الإجابة النموذجية | الدرجة المستحقة |
| :--- | :--- | :--- | :--- |
| س1 (1-4) | اختيار من متعدد | الإجابات الصحيحة: 1-(ب)، 2-(أ)، 3-(أ)، 4-(أ) | 6 درجات |
| س2 (1-3) | صح وخطأ | 1: صحيح، 2: خطأ مع التصحيح، 3: صحيح | 6 درجات |
| س3 المقالي 1 | صياغة ومثال | 2 درجة للدقة العلمية + 2 درجة لسلامة المثال | 4 درجات |
| س3 المقالي 2 | مقارنة وجدول | 2 درجة لأوجه الشبه + 2 درجة لأوجه الاختلاف | 4 درجات |
${additionalPoints}
`;
  }

  if (contentType === "ورقة عمل تفاعلية") {
    return `# 📐 ورقة عمل تدريبية تفاعلية: ${topic}

- **اسم الطالب/ـة:** ....................................................
- **المادة الدراسية:** ${subject}
- **الصف والشعبة:** ${gradeLevel}
- **مستوى النشاط:** متدرج (مبتدئ • متوسط • تحدي)

---

### 🌟 النشاط الأول (المستوى التأسيسي): استرجع واكتشف (3 درجات)
- اكتب تعليقاً علمياً مقتضباً يوضح مفهوم **(${topic})**:
  ................................................................................................................................................................

- صل المصطلح العلمي في العمود (أ) بما يناسبه من العمود (ب):
  - **(أ) الركن الأساسي لـ ${topic}** ⟵ ⟵ **(ب) التطبيق المباشر في المحيط**
  - **(أ) النتيجة المتوقعة** ⟵ ⟵ **(ب) القاعدة العلمية العامة**

---

### 🎯 النشاط الثاني (المستوى المتوسط): فكر وطبق (4 درجات)
قم بتحليل المسألة/الموقف التالي المتعلق بـ **(${topic})**:
> *"إذا واجهت موقفاً تعليمياً يتطلب منك استخدام مبادئ ${topic} في بيئتك الصفية أو المنزلية، ما الخطوات الثلاث التي تتبعها؟"*

1. الخطوة الأولى: ...................................................................................................................
2. الخطوة الثانية: ...................................................................................................................
3. الخطوة الثالثة: ...................................................................................................................

---

### 🏆 النشاط الثالث (مستوى التحدي والإتقان): الإبداع والربط (3 درجات)
- صمّم خريطة ذهنية أو رسماً تخطيطياً في المساحة أدناه يوضح العلاقة بين عناصر **(${topic})** وكيف تتكامل مع بعضها البعض:

\`\`\`
[           مساحة مخصصة للرسم التخطيطي والخريطة الذهنية للطالب           ]
\`\`\`

---
*💡 إضاءة للمعلم: تستهدف ورقة العمل مراعاة الفروق الفردية عبر التدرج في صياغة الأنشطة وتحفيز التفكير الذاتي.*
${additionalPoints}
`;
  }

  if (contentType === "شرح وتبسيط مفاهيم") {
    return `# 💡 شرح وتبسيط المفهوم التعليمي: ${topic}

- **المادة:** ${subject}
- **الفئة المستهدفة:** ${gradeLevel}
- **الأسلوب:** أمثلة تشبيهية، تبسيط المفاهيم، وحوار تعليمي شائق

---

## 🌟 1. الفكرة في سطرين (ما هو ${topic} ببساطة؟)
تخيّل أن مفهوم **(${topic})** يشبه مفتاحاً سحرياً يساعدنا على فهم وترتيب الأمور في مادة ${subject}. بكلمات بسيطة: إنه الأسلوب الذي يربط بين الأسباب والنتائج لنتعلم كيف تعمل الأشياء من حولنا.

---

## 🚗 2. التشبيه اليومي (لتقريب الفكرة إلى ذهن الطالب)
- لكي نتصور **(${topic})** بوضوح، لنتخيل أننا نقود سيارة ذكية:
  - القواعد الأساسية هي عجلة القيادة التي توجهنا.
  - المعطيات هي الوقود الذي يحركنا.
  - والتطبيق الصحيح لـ **(${topic})** هو الوصول الآمن إلى وجهتنا.
هكذا تماماً، عندما نفهم **(${topic})**، نتحول من مرحلة الحفظ المجرد إلى القيادة والتحكم بفهم وإتقان!

---

## 🔍 3. العناصر والمراحل الجوهرية
1. **المرحلة الأولى - الأساس المتين:** التعرف على المدخلات والمصطلحات الرئيسية.
2. **المرحلة الثانية - التفاعل والتركيب:** ملاحظة كيف تتغير النتائج عند تغير الشروط.
3. **المرحلة الثالثة - الاستنتاج والتعميم:** صياغة قاعدة ذهبية نتذكرها دائماً عند حل أي تمرين.

---

## ❓ 4. الأخطاء الشائعة وكيف نتجنبها
- **الخطأ الشائع:** الاعتقاد بأن **(${topic})** مقتصر على القوانين النظرية فقط.
- **التصويب:** الواقع أن **(${topic})** مهارة حية نستخدمها في اتخاذ القرارات وحل المشكلات خطوة بخطوة.

---

## 🎓 5. خلاصة وعبارة ذهبية للحفظ:
> *"الفهم الحقيقي لـ **(${topic})** لا يقاس بكمية ما نحفظه، بل بقدرتنا على شرحه لشخص آخر ببساطة وتطبيقه في مواقف جديدة."*
${additionalPoints}
`;
  }

  // Fallback generic educational content
  return `# 🎓 ${contentType}: ${topic}

- **المادة الدراسية:** ${subject}
- **المرحلة والصف:** ${gradeLevel}
- **الاستراتيجية المقترحة:** ${learningStrategy}
- **الأسلوب:** ${tone}
- **تاريخ الإعداد:** ${dateStr}

---

## 🎯 الأهداف التربوية الرئيسية:
- إكساب المتعلمين المفاهيم الأساسية والمهارات التطبيقية المتعلقة بـ **(${topic})**.
- ترسيخ قيم التفكير الإيجابي والتعلم الذاتي والتعاون الصفي.
- تعزيز قدرة الطالب على التعبير عن أفكاره بثقة واستخدام المصطلحات العلمية السليمة.

---

## 📋 خطة العمل والمحتوى المنظم:
1. **المقدمة والتهيئة:** مدخل استقصائي يستثير الاهتمام ويقيس المعارف السابقة حول **(${topic})**.
2. **الأنشطة التعليمية:** تدريبات وتمارين تفاعلية متدرجة تتناسب مع الفئة العمرية لطلاب ${gradeLevel}.
3. **التقويم والتحقق:** أسئلة شفهية وتحريرية لقياس عمق الفهم والتطبيق.
4. **التوصيات والإثراء:** إرشادات للمعلم لتطوير مستويات الأداء ودعم الطلاب المتميزين وتيسير التعلم للمتعثرين.

---
*تم إعداد هذا المخرج التعليمي وفق أحدث المعايير التربوية والمناهج الدراسية الحديثة.*
${additionalPoints}
`;
}
